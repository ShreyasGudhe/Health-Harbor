# Create singleton instance
gemini_analyzer = GeminiAnalyzer()


def analyze_medical_document(document_text):
    """Convenience function for document analysis"""
    return gemini_analyzer.analyze_document(document_text)


def get_medical_disclaimer():
    """Get the medical disclaimer text"""
    return gemini_analyzer.DISCLAIMER
